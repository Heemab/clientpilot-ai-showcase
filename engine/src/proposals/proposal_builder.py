class ProposalBuilder:
    """
    Builds a professional Markdown proposal from a
    proposal dictionary generated by ProposalGenerator.
    """

    def __init__(self):
        pass

    # --------------------------------------------------
    # Build Markdown Proposal
    # --------------------------------------------------

    def build(self, proposal):

        lines = []

        # --------------------------------------------------
        # Cover
        # --------------------------------------------------

        lines.append("# Website Growth Proposal")
        lines.append("")
        lines.append(f"**Prepared For:** {proposal['business_name']}")
        lines.append(f"**Generated:** {proposal['generated_at']}")
        lines.append("")

        # --------------------------------------------------
        # Executive Summary
        # --------------------------------------------------

        lines.append("## Executive Summary")
        lines.append("")
        lines.append(proposal["executive_summary"])
        lines.append("")

        # --------------------------------------------------
        # Business Snapshot
        # --------------------------------------------------

        lines.append("## Business Snapshot")
        lines.append("")
        lines.append(f"- Category: {proposal['category']}")
        lines.append(f"- Website: {proposal['website']}")
        lines.append(
    f"- Technology: {proposal.get('technology', 'Unknown')}"
        )
        lines.append(f"- Priority: {proposal['priority']}")
        lines.append(f"- Opportunity Score: {proposal['opportunity_score']}")
        lines.append("")

        # --------------------------------------------------
        # Business Opportunities
        # --------------------------------------------------

        lines.append("## Business Opportunities")
        lines.append("")

        insights = proposal.get(
            "business_insights",
            []
        )

        if insights:

            for insight in insights:

                title = insight.get(
                    "title",
                    "Opportunity"
                )

                priority = insight.get(
                    "priority",
                    "Medium"
                )

                impact = insight.get(
                    "impact",
                    ""
                )

                recommendation = insight.get(
                    "recommendation",
                    ""
                )

                category = insight.get(
                    "category",
                    ""
                )

                estimated_value = insight.get(
                    "estimated_value"
                )

                effort = insight.get(
                    "effort_hours"
                )

                lines.append(f"### {title}")
                lines.append("")

                if category:
                    lines.append(f"**Category:** {category}")

                lines.append(f"**Priority:** {priority}")

                if estimated_value is not None:
                    lines.append(
                        f"**Estimated Value:** ${estimated_value:,}"
                    )

                if effort is not None:
                    lines.append(
                        f"**Estimated Effort:** {effort} hours"
                    )

                lines.append("")
                lines.append("**Business Impact**")
                lines.append("")
                lines.append(
                    impact or
                    "Improving this area can strengthen the business's online presence."
                )
                lines.append("")
                lines.append("**Recommendation**")
                lines.append("")
                lines.append(
                    recommendation or
                    "Review this area and implement the recommended improvements."
                )
                lines.append("")
                lines.append("---")
                lines.append("")

        else:

            lines.append(
                "No significant business opportunities were identified during the initial assessment."
            )

            lines.append("")

        # --------------------------------------------------
        # Recommended Services
        # --------------------------------------------------

        lines.append("## Recommended Services")
        lines.append("")

        services = proposal.get(
            "recommended_services",
            []
        )

        if services:

            for service in services:

                lines.append(f"- {service}")

        else:

            lines.append(
                "- No additional services recommended."
            )

        lines.append("")

        # --------------------------------------------------
        # Investment Summary
        # --------------------------------------------------

        lines.append("## Investment Summary")
        lines.append("")
        lines.append(
            f"**Estimated Investment:** ${proposal['investment']:,}"
        )
        lines.append(
            f"**Estimated Timeline:** {proposal['timeline']}"
        )
        lines.append(
            f"**Estimated Hours:** {proposal['estimated_hours']}"
        )
        lines.append(
            f"**Difficulty:** {proposal['difficulty']}"
        )
        lines.append(
            f"**ROI Score:** {proposal['roi_score']}"
        )
        lines.append("")

        # --------------------------------------------------
        # Expected Business Outcomes
        # --------------------------------------------------

        lines.append("## Expected Business Outcomes")
        lines.append("")

        for result in proposal["expected_results"]:

            lines.append(f"✓ {result}")

        lines.append("")

        # --------------------------------------------------
        # Why This Matters
        # --------------------------------------------------

        lines.append("## Why This Matters")
        lines.append("")
        lines.append(proposal["sales_reason"])
        lines.append("")

        # --------------------------------------------------
        # Recommended Next Step
        # --------------------------------------------------

        lines.append("## Recommended Next Step")
        lines.append("")
        lines.append(proposal["next_steps"])
        lines.append("")

        # --------------------------------------------------
        # Closing
        # --------------------------------------------------

        lines.append("---")
        lines.append("")
        lines.append(
            "Thank you for taking the time to review this proposal."
        )
        lines.append("")
        lines.append(
            "Our objective is to help your business generate more enquiries, "
            "strengthen customer trust, and improve your online visibility "
            "through practical, high-impact improvements."
        )
        lines.append("")
        lines.append(
            "The recommendations presented in this report are prioritised to "
            "deliver the greatest business impact while providing a clear "
            "implementation roadmap."
        )
        lines.append("")
        lines.append(
            "I would welcome the opportunity to discuss these findings and "
            "prepare a tailored implementation plan for your business."
        )
        lines.append("")
        lines.append("---")
        lines.append("")
        lines.append("## About ClientPilot")
        lines.append("")
        lines.append(
            "ClientPilot helps businesses improve their online presence through "
            "website optimisation, SEO, automation, and digital growth solutions."
        )
        lines.append("")
        lines.append("### Services")
        lines.append("")
        lines.append("- Website Development")
        lines.append("- WordPress Development")
        lines.append("- Website Audits")
        lines.append("- SEO Optimisation")
        lines.append("- AI Automation")
        lines.append("- Business Process Automation")
        lines.append("")
        lines.append("### Portfolio")
        lines.append("")
        lines.append("https://portfolio.example.invalid")
        lines.append("")
        lines.append("### Next Step")
        lines.append("")
        lines.append(
            "If these recommendations align with your business goals, "
            "I'd be happy to discuss the project and prepare a tailored implementation plan."
        )
        lines.append("")
        lines.append("Kind regards,")
        lines.append("")
        lines.append("ClientPilot Team")
        lines.append("Founder | ClientPilot")
        lines.append("Digital Growth & AI Automation Consultant")
        lines.append("")
        lines.append("Portfolio")
        lines.append("https://portfolio.example.invalid")
        lines.append("")

        return "\n".join(lines)