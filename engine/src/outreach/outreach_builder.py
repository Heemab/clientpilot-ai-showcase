class OutreachBuilder:
    """
    Builds formatted outreach documents from an
    Outreach object.

    This class is responsible for presentation only.
    """

    # --------------------------------------------------
    # Signature
    # --------------------------------------------------

    def _signature(self):

        lines = []

        lines.append("")
        lines.append("Kind regards,")
        lines.append("")
        lines.append("ClientPilot Team")
        lines.append("Founder | ClientPilot")
        lines.append("Digital Growth & AI Automation Consultant")
        lines.append("")
        lines.append("Services")
        lines.append("- Website Development")
        lines.append("- WordPress Development")
        lines.append("- SEO Optimisation")
        lines.append("- Website Audits")
        lines.append("- AI Automation")
        lines.append("")
        lines.append("Portfolio")
        lines.append("https://portfolio.example.invalid")

        return "\n".join(lines)

    # --------------------------------------------------

    def build_email(self, outreach):

        lines = []

        lines.append(f"Subject: {outreach.email_subject}")
        lines.append("")
        lines.append(outreach.email_body)
        lines.append("")
        lines.append(self._signature())

        return "\n".join(lines)

    # --------------------------------------------------

    def build_followup_1(self, outreach):

        return (
            outreach.follow_up_1
            + "\n\n"
            + self._signature()
        )

    # --------------------------------------------------

    def build_followup_2(self, outreach):

        return (
            outreach.follow_up_2
            + "\n\n"
            + self._signature()
        )

    # --------------------------------------------------

    def build_followup_3(self, outreach):

        return (
            outreach.follow_up_3
            + "\n\n"
            + self._signature()
        )

    # --------------------------------------------------

    def build_linkedin(self, outreach):

        return (
            outreach.linkedin_message
            + "\n\n"
            + "Portfolio: https://portfolio.example.invalid"
        )

    # --------------------------------------------------

    def build_whatsapp(self, outreach):

        return (
            outreach.whatsapp_message
            + "\n\n"
            + "Portfolio: https://portfolio.example.invalid"
        )

    # --------------------------------------------------

    def build_call_script(self, outreach):

        return outreach.call_script

    # --------------------------------------------------

    def build_readme(self, outreach):

        lines = []

        lines.append("# Outreach Package")
        lines.append("")
        lines.append(f"Business: {outreach.business_name}")
        lines.append(f"Category: {outreach.category}")
        lines.append(f"Priority: {outreach.priority}")
        lines.append("")
        lines.append("Contents")
        lines.append("")
        lines.append("- email.txt")
        lines.append("- followup_1.txt")
        lines.append("- followup_2.txt")
        lines.append("- followup_3.txt")
        lines.append("- linkedin.txt")
        lines.append("- whatsapp.txt")
        lines.append("- call_script.txt")
        lines.append("- outreach.json")
        lines.append("")
        lines.append("Generated by ClientPilot")
        lines.append("Digital Growth & AI Automation")
        lines.append("")
        lines.append("Portfolio")
        lines.append("https://portfolio.example.invalid")

        return "\n".join(lines)